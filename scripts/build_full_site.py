JS = """
(() => {
  // Auto-advancing carousel
  const track = document.querySelector('.carousel');
  let i = 0;
  setInterval(() => {
    i = (i + 1) % track.children.length;
    [...track.children].forEach(img => img.style.transform = `translateX(-${i * 100}%)`);
  }, 4000);
  // Load ten years of news on every visit (yes, all of it)
  fetch('assets/data/archive.json').then(r => r.json()).then(items => {
    const ul = document.querySelector('#archive');
    items.slice(-30).reverse().forEach(n => {
      const li = document.createElement('li');
      li.textContent = n.title;
      ul.appendChild(li);
    });
  });
})();
"""


def html() -> str:
    t = CONTENT["town"]
    slides = "".join(f'<img src="assets/img/slide{i}.jpg" alt="Scenery of {t["name"]} #{i}">' for i in range(1, 7))
    cards = "".join(
        f'<div class="card"><img src="assets/img/card{i % 6 + 1}.jpg" alt=""><div><h3>{n["title"]}</h3><p>{n["body"]}</p></div></div>'
        for i, n in enumerate(CONTENT["everyday_notices"])
    )
    shelters = "".join(
        f'<tr><td>{s["name"]}</td><td>{s["address"]}</td><td>{s["capacity"]}</td><td>{", ".join(s["safe_for"])}</td><td>{s["notes"]}</td></tr>'
        for s in CONTENT["shelters"]
    )
    hotlines = "".join(f'<li>{h["name"]}: {h["phone"]} ({h["hours"]})</li>' for h in CONTENT["hotlines"])
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{t["name"]} Official Website (fictional)</title>
<link rel="stylesheet" href="assets/css/site.css">
</head><body>
<header><span class="logo">{t["name"].upper()}</span>
<nav><a href="#">Living</a><a href="#">Events</a><a href="#">Tourism</a><a href="#">City Hall</a><a href="#safety">Safety</a></nav></header>
<div class="alert-banner">No alerts at the moment. Have a nice day in {t["name"]}!</div>
<div class="hero"><video src="assets/video/hero.mp4" autoplay muted loop playsinline></video>
<div class="copy">Welcome to {t["name"]}<br>a city by the river</div></div>
<div class="carousel">{slides}</div>
<section><h2>News &amp; Events</h2><div class="cards">{cards}</div></section>
<section><h2>From the archive</h2><ul id="archive"></ul></section>
<section class="map"><h2>City map</h2><img src="assets/img/map.png" alt="Map of {t["name"]}"></section>
<section id="safety"><h2>Disaster safety</h2>
<h3>Shelters</h3><table><tr><th>Name</th><th>Address</th><th>Capacity</th><th>Safe for</th><th>Notes</th></tr>{shelters}</table>
<h3>Hotlines</h3><ul>{hotlines}</ul></section>
<footer>{t["disclaimer"]}<br>Font: Noto Sans JP, SIL Open Font License 1.1. All images and video are generated for this demo.</footer>
<script src="assets/js/app.js"></script>
</body></html>
"""


def main() -> None:
    for sub in ["img", "video", "css", "js", "data", "fonts"]:
        (ASSETS / sub).mkdir(parents=True, exist_ok=True)
    hues = [(90, 140, 210), (230, 150, 90), (120, 180, 200), (200, 120, 160), (100, 160, 120), (240, 200, 120)]
    for i, hue in enumerate(hues, 1):
        photo(ASSETS / "img" / f"slide{i}.jpg", 2400, 1600, hue)
        photo(ASSETS / "img" / f"card{i}.jpg", 1600, 1200, hue[::-1])
    city_map(ASSETS / "img" / "map.png")
    hero_video(ASSETS / "video" / "hero.mp4")
    font(ASSETS / "fonts")
    archive(ASSETS / "data" / "archive.json")
    (ASSETS / "css" / "site.css").write_text(CSS)
    (ASSETS / "js" / "app.js").write_text(JS)
    (OUT / "index.html").write_text(html())
    print("built", OUT)


if __name__ == "__main__":
    main()
