"""Build the deliberately heavy "everyday" site for Example City (site/full/).

Everything here is generated by this script (images, video, map) except the
font, which is an OFL-licensed Google Font downloaded at build time.
Run:  uv run python scripts/build_full_site.py
"""

from __future__ import annotations

import json
import random
import subprocess
import urllib.request
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageOps

ROOT = Path(__file__).resolve().parents[1]
CONTENT = json.loads((ROOT / "content" / "town.json").read_text())
OUT = ROOT / "site" / "full"
ASSETS = OUT / "assets"
FONT_URL = "https://github.com/google/fonts/raw/main/ofl/notosansjp/NotoSansJP%5Bwght%5D.ttf"
FONT_LICENSE_URL = "https://github.com/google/fonts/raw/main/ofl/notosansjp/OFL.txt"

random.seed(42)


def photo(path: Path, w: int, h: int, hue: tuple[int, int, int]) -> None:
    """A fake 'photo': gradient sky, noisy hills, blurred. Big on purpose."""
    grad = Image.linear_gradient("L").resize((w, h))
    img = ImageOps.colorize(grad, black=hue, white=(40, 90, 60))
    noise = Image.effect_noise((w, h), 60).convert("RGB")
    img = Image.blend(img, noise, 0.18)
    d = ImageDraw.Draw(img)
    for i in range(6):
        base = int(h * (0.55 + i * 0.07))
        pts = [(x, base + random.randint(-40, 40)) for x in range(0, w + 200, 200)]
        d.polygon(pts + [(w, h), (0, h)], fill=(30 + i * 15, 70 + i * 12, 40 + i * 8))
    img.filter(ImageFilter.GaussianBlur(1.2)).save(path, "JPEG", quality=95)


def city_map(path: Path) -> None:
    """A big hand-made map of the fictional city: river, roads, shelter pins."""
    w, h = 3200, 2400
    img = Image.new("RGB", (w, h), (233, 236, 228))
    d = ImageDraw.Draw(img)
    river = [(0, 1500), (600, 1350), (1200, 1450), (1800, 1250), (2400, 1350), (3200, 1150)]
    d.line(river, fill=(120, 170, 220), width=140)
    for _ in range(260):
        x, y = random.randint(0, w), random.randint(0, h)
        d.line([(x, y), (x + random.randint(-400, 400), y + random.randint(-400, 400))], fill=(255, 255, 255), width=random.choice([6, 10, 18]))
    for _ in range(900):
        x, y = random.randint(0, w), random.randint(0, h)
        d.rectangle([x, y, x + random.randint(20, 70), y + random.randint(20, 70)], fill=(210, 205, 196))
    for i, s in enumerate(CONTENT["shelters"]):
        x, y = 400 + i * 450, 500 + (i % 3) * 500
        d.ellipse([x - 40, y - 40, x + 40, y + 40], fill=(214, 64, 52))
        d.text((x + 50, y - 10), s["name"], fill=(20, 20, 20))
    img.save(path, "PNG")


def hero_video(path: Path) -> None:
    """A 12-second full-HD background loop, generated with ffmpeg's mandelbrot source."""
    subprocess.run(
        ["ffmpeg", "-y", "-loglevel", "error", "-f", "lavfi", "-i", "mandelbrot=s=1920x1080:rate=30",
         "-t", "12", "-c:v", "libx264", "-crf", "24", "-pix_fmt", "yuv420p", "-an", str(path)],
        check=True,
    )


def font(dir_: Path) -> None:
    """Noto Sans JP (SIL Open Font License 1.1) - a typical heavy web font."""
    dir_.mkdir(parents=True, exist_ok=True)
    for url, name in [(FONT_URL, "NotoSansJP.ttf"), (FONT_LICENSE_URL, "OFL.txt")]:
        target = dir_ / name
        if not target.exists():
            urllib.request.urlretrieve(url, target)


def archive(path: Path) -> None:
    """Ten years of everyday news, loaded by JavaScript on every visit."""
    topics = ["festival", "garbage", "library", "tax", "parks", "school", "roads", "sports", "health", "tourism"]
    items = []
    for i in range(6000):
        t = random.choice(topics)
        items.append({"id": i, "topic": t, "title": f"Notice #{i} about {t}",
                      "body": f"Example City update on {t}. " * random.randint(5, 15)})
    path.write_text(json.dumps(items))


